#!/usr/bin/env python3
# ──────────────────────────────────────────────────────────
# [Clean Architecture] Infrastructure Layer - Build Tool
#
# 역할: 일본어·중국어 입력기 변환 사전 생성 (apps/keyboard/dict/*.js)
# 수행범위: 허용형 라이선스 원본에서 빈도 상위 항목만 골라 키보드가 지연
#           로드하는 ES5 데이터 파일과 라이선스 고지 파일을 만든다
# 의존방향: Python 표준 라이브러리만
# SOLID: SRP — 사전 데이터 변환만 담당
#
# Sources (download into an empty directory, pass the paths here):
#   zh: AOSP PinyinIME jni/data/rawdict_utf16_65105_freq.txt (Apache-2.0)
#       + its NOTICE
#   ja: Mozc src/data/dictionary_oss/dictionary0[0-9].txt, id.def, README.txt
#       (IPAdic / ICOT / Okinawa dictionary / Google BSD-3) + mozc LICENSE
#
#   python3 -I tools/build_ime_dict.py --pinyin rawdict.txt --pinyin-notice NOTICE \
#       --mozc-dir mozc/ --mozc-license mozc/LICENSE --out apps/keyboard/dict
# ──────────────────────────────────────────────────────────

import argparse
import collections
import glob
import json
import os
import re

JA_ENTRIES = 40000   # ~1 MB; covers everyday vocabulary, drops the long tail

HEADER = """// ----------------------------------------------------------
// [Clean Architecture] Domain Layer - Input Method Data ({lang})
//
// Role: {role}
// Scope: reading -> candidates, most frequent first, one line per reading
// Dependency Direction: Domain -> ZylImeDict (apps/keyboard/js/ime.js)
// SOLID: SRP — data only. Generated by tools/build_ime_dict.py; do not edit.
//
// Source and licenses: apps/keyboard/dict/LICENSES.txt
// ----------------------------------------------------------
"""

# Characters that would break the line format or an ES5 string literal
UNSAFE = re.compile(r'[\s`\'"\\\x00-\x1f  ]')
KATAKANA = re.compile(r'^[゠-ヿ]+$')


def write_js(path, lang, role, groups):
    lines = []
    for key in sorted(groups):
        words = [w for _, w in sorted(groups[key])]
        lines.append(key + '\t' + ' '.join(words))
    text = json.dumps('\n'.join(lines), ensure_ascii=False)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(HEADER.format(lang=lang, role=role))
        f.write("ZylImeDict.register('%s', %s);\n" % (lang, text))
    return len(groups)


def build_zh(src):
    raw = open(src, 'rb').read()
    text = raw.decode('utf-16')
    groups = collections.defaultdict(list)
    for line in text.splitlines():
        parts = line.split(' ')
        # word freq not_gb2312 syllable...  — keep simplified (GB2312) entries
        if len(parts) < 4 or parts[2] != '0' or UNSAFE.search(parts[0]):
            continue
        groups[''.join(parts[3:])].append((-float(parts[1]), parts[0]))
    return groups


def build_ja(mozc_dir):
    pos = {}
    for line in open(os.path.join(mozc_dir, 'id.def'), encoding='utf-8'):
        i, name = line.split(' ', 1)
        pos[int(i)] = name.strip()

    def wanted(p):
        # Personal, place and organisation names are most of the long tail and
        # crowd out common words; country names stay
        if p.startswith('名詞,固有名詞,'):
            return p.startswith('名詞,固有名詞,地域,国')
        return not p.startswith('名詞,数,アラビア数字')

    best = {}
    for path in sorted(glob.glob(os.path.join(mozc_dir, 'dictionary0*.txt'))):
        for line in open(path, encoding='utf-8'):
            p = line.rstrip('\n').split('\t')
            if len(p) != 5:
                continue
            reading, left, _, cost, surface = p
            # Hiragana as typed and its katakana are generated by the IME itself
            if surface == reading or KATAKANA.match(surface) or UNSAFE.search(surface):
                continue
            if not wanted(pos.get(int(left), '')):
                continue
            k = (reading, surface)
            c = int(cost)
            if k not in best or c < best[k]:
                best[k] = c
    groups = collections.defaultdict(list)
    for (reading, surface), cost in sorted(best.items(), key=lambda kv: kv[1])[:JA_ENTRIES]:
        groups[reading].append((cost, surface))
    return groups


def licenses(out, pinyin_notice, mozc_license, mozc_readme):
    readme = open(mozc_readme, encoding='utf-8').read()
    terms = readme[readme.index('IPAdic is licensed as follows'):]
    with open(os.path.join(out, 'LICENSES.txt'), 'w', encoding='utf-8') as f:
        f.write('Zyl OS input method dictionaries — sources and licenses\n\n')
        f.write('zh.js is derived from AOSP PinyinIME '
                'jni/data/rawdict_utf16_65105_freq.txt (simplified entries only).\n')
        f.write('ja.js is derived from the Mozc open source dictionary '
                '(src/data/dictionary_oss): the %d most frequent entries,\n'
                'proper names other than countries removed.\n\n' % JA_ENTRIES)
        f.write('=' * 72 + '\nAOSP PinyinIME NOTICE\n' + '=' * 72 + '\n')
        f.write(open(pinyin_notice, encoding='utf-8').read())
        f.write('\n' + '=' * 72 + '\nMozc LICENSE\n' + '=' * 72 + '\n')
        f.write(open(mozc_license, encoding='utf-8').read())
        f.write('\n' + '=' * 72 + '\nMozc dictionary_oss data licenses (README.txt)\n' + '=' * 72 + '\n')
        f.write(terms)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--pinyin', required=True)
    ap.add_argument('--pinyin-notice', required=True)
    ap.add_argument('--mozc-dir', required=True)
    ap.add_argument('--mozc-license', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    n = write_js(os.path.join(a.out, 'zh.js'), 'zh',
                 'Pinyin (ü typed as v) -> simplified Chinese words', build_zh(a.pinyin))
    print('zh readings:', n)
    n = write_js(os.path.join(a.out, 'ja.js'), 'ja',
                 'Hiragana reading -> kanji / mixed Japanese words', build_ja(a.mozc_dir))
    print('ja readings:', n)
    licenses(a.out, a.pinyin_notice, a.mozc_license, os.path.join(a.mozc_dir, 'README.txt'))


if __name__ == '__main__':
    main()
