#!/bin/bash
# ──────────────────────────────────────────────────────────
# [Clean Architecture] Infrastructure Layer - Bootloader Build
#
# 역할: BPI-F3(SpacemiT K1) 부트로더를 Zyl OS 키와 부트 정책으로 빌드·서명
# 수행범위: 고정한 제조사 U-Boot·OpenSBI 커밋 → Zyl 패치(부트 정책, 칩 ID 기기
#           ID, 선택 시 eFuse 굽기) + 설정 조각 → 빌드 →
#           FSBL: 루트 키(zylos-rotpk)로 헤더, zylos-spl-key 로 SPL 서명 (Boot ROM 검증)
#           OpenSBI·U-Boot FIT: zylos-fw-key 서명, 공개키는 SPL DTB 에 required
#           U-Boot DTB 들: OS 키(zylos-boot-key) required — 커널 FIT 검증
#           기본 환경 = board/bpi-f3/u-boot-env.txt, 저장소가 쓸 수 있는 변수는
#           그 파일의 "Runtime state" 절만 → 결과물을 다시 검사(서명·키·설정)
# 의존방향: git, make, riscv64 크로스 gcc, python3(+yaml), openssl, dtc, xxd,
#           board/bpi-f3/bootloader/*, tools/gen-boot-keys.sh 의 키
# SOLID: SRP — 부트로더 빌드만 담당
#
# 사용법: tools/build-bootloader.sh [--key-dir DIR] [--burn-rotpk] [output-dir]
#   --burn-rotpk  eFuse 에 루트 공개키 해시를 굽는 부트로더 (되돌릴 수 없음,
#                 docs/INSTALLATION_INFORMATION.md). 기본은 굽지 않는다
#   ZYL_UBOOT_SRC / ZYL_OPENSBI_SRC  고정 커밋의 로컬 사본 (없으면 받아 온다)
#   CROSS_COMPILE  기본 riscv64-linux-gnu-
# 출력: FSBL.bin bootinfo_emmc.bin bootinfo_sd.bin fw_dynamic.itb u-boot.itb
#       u-boot-env-default.bin rotpk-sha256.txt MANIFEST.sha256
# ──────────────────────────────────────────────────────────
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BOOT="$ROOT/board/bpi-f3/bootloader"
ENV_FILE="$ROOT/board/bpi-f3/u-boot-env.txt"

# The vendor's K1 boot firmware, branch k1-bl-v2.2.y — pinned: what is signed is
# exactly this source plus board/bpi-f3/bootloader
UBOOT_REPO=https://github.com/spacemit-com/uboot-2022.10.git
UBOOT_COMMIT=7f51f4453f9811eeaafbdd839b1bf1b0cc27a413
OPENSBI_REPO=https://github.com/spacemit-com/opensbi.git
OPENSBI_COMMIT=fc02b891b17b8bdc1273a39f80aa374cd99ba9a2

KEY_DIR="$ROOT/board/bpi-f3/keys"
BURN=0
while [ $# -gt 0 ]; do
    case "$1" in
        --key-dir)    KEY_DIR="$2"; shift 2 ;;
        --burn-rotpk) BURN=1; shift ;;
        -*) echo "✗ unknown option $1" >&2; exit 2 ;;
        *) break ;;
    esac
done
OUT="${1:-build/bootloader}"
CROSS_COMPILE="${CROSS_COMPILE:-riscv64-linux-gnu-}"
export CROSS_COMPILE ARCH=riscv

for c in git make python3 openssl dtc fdtget xxd "${CROSS_COMPILE}gcc"; do
    command -v "$c" >/dev/null 2>&1 || { echo "✗ Required command not found: $c" >&2; exit 1; }
done
python3 -c 'import yaml' 2>/dev/null || { echo "✗ python3 yaml module needed (vendor build_binary_file.py)" >&2; exit 1; }
for k in zylos-boot-key.key zylos-boot-key.crt zylos-fw-key.key zylos-fw-key.crt zylos-spl-key.key zylos-rotpk.key; do
    [ -f "$KEY_DIR/$k" ] || { echo "✗ $KEY_DIR/$k missing — tools/gen-boot-keys.sh $KEY_DIR" >&2; exit 1; }
done
KEY_DIR="$(cd "$KEY_DIR" && pwd)"
mkdir -p "$OUT"
OUT="$(cd "$OUT" && pwd)"
W="$OUT/work"
rm -rf "$W"
mkdir -p "$W"
JOBS="$(getconf _NPROCESSORS_ONLN 2>/dev/null || echo 4)"
step() { echo "▸ $*"; }

# A pinned commit: from a local copy, or fetched shallow
source_tree() {   # repo commit local-copy dest
    if [ -n "$3" ]; then
        cp -a "$3" "$4"
    else
        git init -q "$4"
        git -C "$4" fetch -q --depth 1 "$1" "$2"
        git -C "$4" checkout -q FETCH_HEAD
    fi
    [ "$(git -C "$4" rev-parse HEAD)" = "$2" ] || { echo "✗ $4 is not at $2" >&2; exit 1; }
}

echo "═══ Zyl OS bootloader (BPI-F3, SpacemiT K1)$([ $BURN = 1 ] && echo ' — burns the root key hash into eFuse') ═══"
step "sources (U-Boot ${UBOOT_COMMIT:0:12}, OpenSBI ${OPENSBI_COMMIT:0:12})"
source_tree "$UBOOT_REPO" "$UBOOT_COMMIT" "${ZYL_UBOOT_SRC:-}" "$W/u-boot"
source_tree "$OPENSBI_REPO" "$OPENSBI_COMMIT" "${ZYL_OPENSBI_SRC:-}" "$W/opensbi"
U="$W/u-boot"
git -C "$U" apply "$BOOT/0001-zyl-os-boot-policy.patch"

# ── Keys: the vendor tree ships its own (private!) — none of them may remain ──
step "keys"
FK="$U/board/spacemit/k1-x/configs/key"
rm -f "$FK"/*
cp "$KEY_DIR/zylos-rotpk.key" "$FK/rsakeypair0_prv.key"
cp "$KEY_DIR/zylos-spl-key.key" "$FK/spl_pubkey_prv.key"
openssl pkey -in "$KEY_DIR/zylos-fw-key.key" -pubout -out "$FK/uboot_pubkey_pub.key"
openssl pkey -in "$KEY_DIR/zylos-boot-key.key" -pubout -out "$FK/kernel_pubkey_pub.key"
cp "$FK/kernel_pubkey_pub.key" "$FK/rootfs_pubkey_pub.key"

# ── The boot policy, and the variables storage may set (its Runtime state) ──
step "boot policy (board/bpi-f3/u-boot-env.txt)"
sed -e "s/^zyl_rotpk_burn=.*/zyl_rotpk_burn=$BURN/" "$ENV_FILE" > "$U/board/spacemit/k1-x/zyl-env.txt"
python3 -I - "$ENV_FILE" > "$U/include/zyl_env_flags.h" <<'PY'
import re, sys
names, inside = [], False
for line in open(sys.argv[1]):
    if line.startswith('# ──'):
        inside = line.startswith('# ── Runtime state')
    elif inside and re.match(r'^[A-Za-z_][A-Za-z0-9_]*=', line):
        names.append(line.split('=', 1)[0])
if not names:
    sys.exit('no Runtime state variables in ' + sys.argv[1])
print('/* Generated by tools/build-bootloader.sh from board/bpi-f3/u-boot-env.txt */')
print('#define CONFIG_ENV_FLAGS_LIST_STATIC "%s"' % ','.join(n + ':sw' for n in names))
PY
# Placeholder until the FSBL exists (only CONFIG_ZYL_ROTPK_BURN reads it)
printf '#define ZYL_FSBL_SIZE 0\n#define ZYL_FSBL_SHA256 { 0 }\n' > "$U/include/zyl_rotpk.h"

# ── Configuration: the vendor's plus ours, and ours must have stuck ──
step "configuration"
{
    cat "$BOOT/uboot.config"
    echo 'CONFIG_DEFAULT_ENV_FILE="board/spacemit/k1-x/zyl-env.txt"'
    [ $BURN = 1 ] && echo 'CONFIG_ZYL_ROTPK_BURN=y' || echo '# CONFIG_ZYL_ROTPK_BURN is not set'
} > "$W/zyl.config"
( cd "$U" && make -s k1_defconfig && scripts/kconfig/merge_config.sh -m .config "$W/zyl.config" >/dev/null \
  && make -s olddefconfig )
while IFS= read -r line; do
    case "$line" in
        CONFIG_*=*) grep -qxF "$line" "$U/.config" || { echo "✗ not in .config: $line" >&2; exit 1; } ;;
        "# CONFIG_"*" is not set") n="${line#\# }"; n="${n%% *}"
            ! grep -q "^$n=" "$U/.config" || { echo "✗ still set: $n" >&2; exit 1; } ;;
    esac
done < "$W/zyl.config"

step "U-Boot and SPL"
make -C "$U" -s -j"$JOBS" >"$W/u-boot.log" 2>&1 || { tail -30 "$W/u-boot.log"; exit 1; }

step "OpenSBI"
make -C "$W/opensbi" -s -j"$JOBS" PLATFORM=generic PLATFORM_DEFCONFIG=k1_defconfig MKIMAGE="$U/tools/mkimage" \
    >"$W/opensbi.log" 2>&1 \
    || { tail -30 "$W/opensbi.log"; exit 1; }

# The vendor's FIT sources with SHA-256 hashes and every configuration signed
signed_its() {   # its-in key-name-hint its-out
    python3 -I - "$1" "$2" > "$3" <<'PY'
import re, sys
text, key = open(sys.argv[1]).read(), sys.argv[2]
text = text.replace('algo = "crc32";', 'algo = "sha256";')
head, sep, confs = text.partition('configurations {')
def sign(m):
    body = m.group(3)
    images = [p for p in ('firmware', 'loadables', 'fdt') if re.search(r'^\s*%s\s*=' % p, body, re.M)]
    ind = m.group(1) + '\t'
    node = ('%ssignature-1 {\n%s\talgo = "sha256,rsa2048";\n%s\tkey-name-hint = "%s";\n'
            '%s\tsign-images = %s;\n%s};\n') % (ind, ind, ind, key, ind,
            ', '.join('"%s"' % i for i in images), ind)
    return '%s%s {\n%s%s%s};' % (m.group(1), m.group(2), body, node, m.group(1))
confs, n = re.subn(r'^(\t+)(\w+) \{\n(.*?)^\1\};', sign, confs, flags=re.M | re.S)
if not sep or not n:
    sys.exit('no configurations in ' + sys.argv[1])
print(head + sep + confs, end='')
PY
}

MKIMAGE="$U/tools/mkimage"
SPL_DTB="$U/spl/u-boot-spl.dtb"

# ── OpenSBI FIT, signed; the key goes into the SPL's DTB as required ──
step "OpenSBI FIT (zylos-fw-key)"
cp "$W/opensbi/build/platform/generic/firmware/fw_dynamic.bin" "$W/fw_dynamic.bin"
signed_its "$W/opensbi/platform/generic/spacemit/fw_dynamic.its" zylos-fw-key "$W/fw_dynamic.its"
"$MKIMAGE" -f "$W/fw_dynamic.its" -k "$KEY_DIR" -K "$SPL_DTB" -r "$OUT/fw_dynamic.itb" >/dev/null

# ── The FSBL: SPL with that DTB, header signed by the root key, SPL by its key ──
step "FSBL (zylos-rotpk, zylos-spl-key)"
SEP_BSS="$(grep -c '^CONFIG_SPL_SEPARATE_BSS=y' "$U/.config" || true)"
cat "$U/spl/u-boot-spl-nodtb.bin" $([ "$SEP_BSS" = 1 ] || echo "$U/spl/u-boot-spl-pad.bin") "$SPL_DTB" \
    > "$U/spl/u-boot-spl.bin"
# The same limit the U-Boot build checks (CONFIG_SPL_SIZE_LIMIT: SRAM up to the SPL's BSS)
SPL_MAX=$("$U/tools/spl_size_limit")
SPL_SIZE=$(wc -c < "$U/spl/u-boot-spl.bin")
[ "$SPL_MAX" -gt 0 ] && [ "$SPL_SIZE" -le "$SPL_MAX" ] \
    || { echo "✗ SPL $SPL_SIZE bytes, limit $SPL_MAX (CONFIG_SPL_SIZE_LIMIT)" >&2; exit 1; }
cp "$U/spl/u-boot-spl.bin" "$U/board/spacemit/k1-x/"
( cd "$U" && python3 tools/build_binary_file.py -c board/spacemit/k1-x/configs/fsbl.json -o FSBL.bin >/dev/null )
rm -f "$U/board/spacemit/k1-x/u-boot-spl.bin"
FSBL_SHA=$(openssl dgst -sha256 -r "$U/FSBL.bin" | cut -c1-64)

# ── With eFuse burning: U-Boot learns exactly which FSBL it may burn for ──
if [ $BURN = 1 ]; then
    step "zyl_rotpk: for this FSBL only (${FSBL_SHA:0:16}…)"
    {
        echo "#define ZYL_FSBL_SIZE $(wc -c < "$U/FSBL.bin")"
        echo "#define ZYL_FSBL_SHA256 { $(echo "$FSBL_SHA" | sed 's/../0x&, /g; s/, $//') }"
    } > "$U/include/zyl_rotpk.h"
    # U-Boot proper only: a full make would rebuild the SPL from its key-less DTB
    make -C "$U" -s -j"$JOBS" u-boot-nodtb.bin >>"$W/u-boot.log" 2>&1 || { tail -30 "$W/u-boot.log"; exit 1; }
    [ "$(openssl dgst -sha256 -r "$U/FSBL.bin" | cut -c1-64)" = "$FSBL_SHA" ] \
        || { echo "✗ the FSBL changed while U-Boot was rebuilt" >&2; exit 1; }
fi

# ── U-Boot FIT: its DTBs carry the OS key (kernel FIT), the FIT is signed ──
step "U-Boot FIT (zylos-fw-key), OS key in its DTBs (zylos-boot-key)"
D="$U/board/spacemit/k1-x/dtb"
rm -rf "$D" && mkdir -p "$D"
cp "$U"/arch/riscv/dts/*.dtb "$D/"
head -c 64 /dev/zero > "$W/none.bin"
cat > "$W/os-key.its" <<EOF
/dts-v1/;
/ {
	description = "writes the OS key into a DTB";
	#address-cells = <1>;
	images { none { data = /incbin/("$W/none.bin"); type = "firmware"; arch = "riscv"; compression = "none";
		hash-1 { algo = "sha256"; }; }; };
	configurations { default = "c"; c { firmware = "none";
		signature-1 { algo = "sha256,rsa2048"; key-name-hint = "zylos-boot-key"; sign-images = "firmware"; }; }; };
};
EOF
for dtb in "$D"/*.dtb; do
    "$MKIMAGE" -f "$W/os-key.its" -k "$KEY_DIR" -K "$dtb" -r "$W/os-key.itb" >/dev/null
done
cp "$U/u-boot-nodtb.bin" "$U/board/spacemit/k1-x/"
signed_its "$U/board/spacemit/k1-x/configs/uboot_fdt.its" zylos-fw-key "$U/board/spacemit/k1-x/configs/zyl-uboot.its"
"$MKIMAGE" -f "$U/board/spacemit/k1-x/configs/zyl-uboot.its" -k "$KEY_DIR" -K "$SPL_DTB" -r "$OUT/u-boot.itb" >/dev/null
rm -f "$U/board/spacemit/k1-x/u-boot-nodtb.bin"

# ── Check everything the way the device will ──
step "verifying"
FK_TMP="$W/pub"
mkdir -p "$FK_TMP"
openssl pkey -in "$KEY_DIR/zylos-rotpk.key" -pubout -out "$FK_TMP/rotpk.pub"
openssl pkey -in "$KEY_DIR/zylos-spl-key.key" -pubout -out "$FK_TMP/spl.pub"
python3 -I - "$U/FSBL.bin" "$KEY_DIR/zylos-rotpk.key" "$FK_TMP" <<'PY'
import hashlib, subprocess, sys
f, key, tmp = open(sys.argv[1], 'rb').read(), sys.argv[2], sys.argv[3]
mod = subprocess.run(['openssl', 'rsa', '-in', key, '-noout', '-modulus'], capture_output=True,
                     text=True, check=True).stdout.strip().split('=')[1]
def verify(data, sig, pub, what):
    open(tmp + '/d', 'wb').write(data)
    open(tmp + '/s', 'wb').write(sig)
    r = subprocess.run(['openssl', 'dgst', '-sha256', '-verify', pub, '-signature', tmp + '/s', tmp + '/d'],
                       capture_output=True)
    if r.returncode:
        sys.exit('✗ FSBL: %s signature does not verify' % what)
# Layout: board/spacemit/k1-x/configs/fsbl.json
assert f[0:256].hex().upper() == mod.upper(), '✗ FSBL: root key is not zylos-rotpk'
assert f[256:260] == b'AIHD' and f[4064:4068] == b'AIHD', '✗ FSBL: headers'
assert f[696:728] == hashlib.sha256(f[0:256]).digest(), '✗ FSBL: rotpk_hash'
verify(f[256:2816], f[2816:3072], tmp + '/rotpk.pub', 'header (root key)')
size = int.from_bytes(f[4072:4080], 'little')
verify(f[4064:4096 + size], f[4096 + size:4096 + size + 256], tmp + '/spl.pub', 'SPL')
PY
[ "$(fdtget "$SPL_DTB" /signature/key-zylos-fw-key required)" = conf ] \
    || { echo "✗ SPL DTB: zylos-fw-key is not required" >&2; exit 1; }
# fit_check_sign checks the signed configuration; a loadable's data the SPL
# hashes as it loads it — so hash every image here too
for itb in fw_dynamic.itb u-boot.itb; do
    "$U/tools/fit_check_sign" -f "$OUT/$itb" -k "$SPL_DTB" >/dev/null || { echo "✗ $itb: signature" >&2; exit 1; }
    python3 -I - "$U/tools/dumpimage" "$OUT/$itb" "$W/image.bin" <<'PY'
import hashlib, re, subprocess, sys
tool, itb, tmp = sys.argv[1:]
listing = subprocess.run([tool, '-l', itb], capture_output=True, text=True, check=True).stdout
images = re.findall(r'^ Image (\d+) \((\S+)\)\n(.*?)(?=^ \S|\Z)', listing, re.M | re.S)
if not images:
    sys.exit('✗ %s: no images' % itb)
for n, name, body in images:
    want = re.search(r'Hash algo:\s+sha256\s+Hash value:\s+([0-9a-f]{64})', body)
    subprocess.run([tool, '-T', 'flat_dt', '-p', n, '-o', tmp, itb], capture_output=True, check=True)
    if not want or hashlib.sha256(open(tmp, 'rb').read()).hexdigest() != want.group(1):
        sys.exit('✗ %s: image %s does not match its signed hash' % (itb, name))
PY
done
for dtb in "$D"/*.dtb; do
    [ "$(fdtget "$dtb" /signature/key-zylos-boot-key required)" = conf ] \
        || { echo "✗ $(basename "$dtb"): OS key is not required" >&2; exit 1; }
done
ROTPK_SHA=$(head -c 256 "$U/FSBL.bin" | openssl dgst -sha256 -r | cut -c1-64)

cp "$U/FSBL.bin" "$U/bootinfo_emmc.bin" "$U/bootinfo_sd.bin" "$U/u-boot-env-default.bin" "$OUT/"
echo "$ROTPK_SHA" > "$OUT/rotpk-sha256.txt"
( cd "$OUT" && openssl dgst -sha256 -r FSBL.bin bootinfo_emmc.bin bootinfo_sd.bin fw_dynamic.itb u-boot.itb \
    u-boot-env-default.bin rotpk-sha256.txt > MANIFEST.sha256 )
rm -rf "$W"

echo "  ✓ FSBL: header signed by zylos-rotpk, SPL by zylos-spl-key"
echo "  ✓ OpenSBI and U-Boot FITs signed by zylos-fw-key, required by the SPL"
echo "  ✓ OS key required by U-Boot; boot policy built in"
echo ""
echo "Root of Trust public key hash: $ROTPK_SHA"
echo "Install (board/bpi-f3/README.md): FSBL.bin + bootinfo_emmc.bin → eMMC boot0,"
echo "  fw_dynamic.itb → partition 'opensbi', u-boot.itb → 'uboot', u-boot-env-default.bin → 'env'"
if [ $BURN = 1 ]; then
    echo "⚠ This U-Boot burns $ROTPK_SHA into eFuse at its first locked boot, if eMMC boot0"
    echo "  holds this FSBL. From then on the Boot ROM runs only FSBLs signed by zylos-rotpk."
    echo "  Irreversible; the vendor does not document the hash format — docs/INSTALLATION_INFORMATION.md"
fi
